def math_block(*lines):
    """Locally rendered MathJax equations, split into readable display lines."""
    expression=r"\begin{gathered}"+r" \\ ".join(lines)+r"\end{gathered}"
    return dcc.Markdown("$$\n"+expression+"\n$$",mathjax=True,className='math-formula')
